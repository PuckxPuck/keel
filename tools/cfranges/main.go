// Command cfranges refreshes the embedded Cloudflare address ranges.
// Run it through `go generate ./internal/kit/httpx`.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"net/netip"
	"os"
	"slices"
	"strings"
	"time"
)

const (
	v4URL    = "https://www.cloudflare.com/ips-v4"
	v6URL    = "https://www.cloudflare.com/ips-v6"
	maxBytes = 64 << 10
)

func main() {
	out := flag.String("out", "cloudflare_ranges.go", "file to write")
	pkg := flag.String("pkg", "httpx", "package name of the generated file")
	flag.Parse()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	var prefixes []netip.Prefix
	for _, url := range []string{v4URL, v6URL} {
		got, err := fetch(ctx, url)
		if err != nil {
			log.Fatalf("cfranges: %v", err)
		}
		prefixes = append(prefixes, got...)
	}
	slices.SortFunc(prefixes, func(a, b netip.Prefix) int { return strings.Compare(a.String(), b.String()) })

	src, err := render(*pkg, time.Now().UTC().Format(time.DateOnly), prefixes)
	if err != nil {
		log.Fatalf("cfranges: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // generated source, not a secret
		log.Fatalf("cfranges: %v", err)
	}
}

func fetch(ctx context.Context, url string) ([]netip.Prefix, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("fetch %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("fetch %s: status %d", url, resp.StatusCode)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, maxBytes))
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", url, err)
	}
	var prefixes []netip.Prefix
	for line := range strings.FieldsSeq(string(body)) {
		p, err := netip.ParsePrefix(line)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", url, err)
		}
		prefixes = append(prefixes, p.Masked())
	}
	if len(prefixes) < 3 {
		return nil, fmt.Errorf("%s: only %d ranges, refusing to write", url, len(prefixes))
	}
	return prefixes, nil
}

func render(pkg, date string, prefixes []netip.Prefix) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/cfranges; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport \"net/netip\"\n\n", pkg)
	fmt.Fprintf(&b, "// CloudflareRangesFetched is the date the lists at %s and %s were fetched.\n", v4URL, v6URL)
	fmt.Fprintf(&b, "const CloudflareRangesFetched = %q\n\n", date)
	b.WriteString("var cloudflareRanges = []netip.Prefix{\n")
	for _, p := range prefixes {
		fmt.Fprintf(&b, "\tnetip.MustParsePrefix(%q),\n", p.String())
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
