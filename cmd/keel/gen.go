const (
	dbgenDir = "internal/dbgen"
	specDir  = "spec"
)

func genFlags(fs *flag.FlagSet) {
	fs.Bool("check", false, "generate into a temporary directory and fail if internal/dbgen or spec differs")
}

// runGen migrates a scratch database per engine, regenerates the Jet table and model types in
// internal/dbgen/<dialect>/{table,model} and exports each realm's OpenAPI document to spec/<realm>.openapi.yaml;
// with --check it only reports drift.
func runGen(ctx context.Context, fs *flag.FlagSet, _ []string) error {
	t, err := repoTree()
	if err != nil {
		return err
	}
	return runGenIn(ctx, fs.Output(), t, fs.Lookup("check").Value.String() == "true")
}

func runGenIn(ctx context.Context, out io.Writer, t *tree, check bool) error {
	dialects := t.dialects()
	if len(dialects) == 0 {
		return errNoDialect
	}
	urls := map[string]string{}
	for _, e := range engines {
		if !slices.Contains(dialects, e.name) {
			continue
		}
		u, ok := e.url(ctx)
		if !ok {
			return fmt.Errorf("db/migrations/%s exists, so keel gen needs a %s database: set %s, or start one with %s (%s)", e.name, e.name, e.urlVar, e.hint, e.unreachable())
		}
		urls[e.name] = u
	}
	var err error
	root := t.root
	if check {
		if root, err = os.MkdirTemp("", "keel-gen-"); err != nil {
			return err
		}
		defer func() { _ = os.RemoveAll(root) }()
	}
	var drift []string
	for _, e := range engines {
		u, ok := urls[e.name]
		if !ok {
			continue
		}
		_, _ = fmt.Fprintf(out, "==> gen %s\n", e.name)
		fsys := os.DirFS(filepath.Join(t.root, migrationsDir, e.name))
		if err := genDialect(ctx, db.Dialect(e.name), u, fsys, filepath.Join(root, dbgenDir, e.name)); err != nil {
			return fmt.Errorf("gen %s: %w", e.name, err)
		}
		if check {
			files, err := differing(filepath.Join(root, dbgenDir, e.name), filepath.Join(t.root, dbgenDir, e.name))
			if err != nil {
				return err
			}
			drift = append(drift, files...)
		}
	}
	_, _ = fmt.Fprintln(out, "==> gen openapi")
	if err := exportSpecs(ctx, t, filepath.Join(root, specDir)); err != nil {
		return fmt.Errorf("gen openapi: %w", err)
	}
	if check {
		files, err := differing(filepath.Join(root, specDir), filepath.Join(t.root, specDir))
		if err != nil {
			return err
		}
		drift = append(drift, files...)
	}
	if len(drift) > 0 {
		return fmt.Errorf("generated code is out of date (run keel gen):\n  %s", strings.Join(drift, "\n  "))
	}
	return nil
}

// snapshot is the content of generated directories, to put back when a generator fails after gen ran.
type snapshot map[string]map[string][]byte

func (t *tree) snapshot(dirs ...string) snapshot {
	out := snapshot{}
	for _, dir := range dirs {
		files, err := readTree(t.path(dir))
		if err == nil {
			out[dir] = files
		}
	}
	return out
}

func (s snapshot) restore(t *tree) error {
	var errs []error
	for dir, want := range s {
		have, err := readTree(t.path(dir))
		if err != nil {
			errs = append(errs, err)
			continue
		}
		for name := range have {
			if _, kept := want[name]; !kept {
				errs = append(errs, os.Remove(filepath.Join(t.path(dir), name)))
			}
		}
		for name, content := range want {
			if !bytes.Equal(have[name], content) {
				errs = append(errs, os.WriteFile(filepath.Join(t.path(dir), name), content, 0o600))
			}
		}
	}
	return errors.Join(errs...)
}

// specHeader marks the exported documents as generated.
const specHeader = "# Code generated by keel gen from the registered operations. DO NOT EDIT.\n"

// exportSpecs builds cmd/app and writes `app openapi --realm <r>` for every realm route:list names.
// humaErrorModel is the schema Huma documents errors with until problem.Install replaces it with Problem.
const humaErrorModel = "#/components/schemas/ErrorModel"

func exportSpecs(ctx context.Context, t *tree, dest string) error {
	bin, err := os.MkdirTemp("", "keel-app-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(bin) }()
	appBin := filepath.Join(bin, "app")
	build := exec.CommandContext(ctx, "go", "build", "-o", appBin, "./cmd/app") //nolint:gosec // a temporary output path
	build.Dir, build.Stderr = t.root, os.Stderr
	build.Env = append(os.Environ(), "CGO_ENABLED=0")
	if err := build.Run(); err != nil {
		return fmt.Errorf("build cmd/app: %w", err)
	}
	routes, err := exec.CommandContext(ctx, appBin, "route:list", "--json").Output() //nolint:gosec // the binary just built
	if err != nil {
		return fmt.Errorf("route:list: %w", err)
	}
	var rows []struct {
		Realm string `json:"realm"`
	}
	if err := json.Unmarshal(routes, &rows); err != nil {
		return fmt.Errorf("route:list: %w", err)
	}
	var realms []string
	for _, r := range rows {
		if !slices.Contains(realms, r.Realm) {
			realms = append(realms, r.Realm)
		}
	}
	if err := os.MkdirAll(dest, 0o750); err != nil {
		return err
	}
	if err := removeStaleSpecs(dest, realms); err != nil {
		return err
	}
	for _, r := range realms {
		doc, err := exec.CommandContext(ctx, appBin, "openapi", "--realm", r).Output() //nolint:gosec // the binary just built, a realm it listed
		if err != nil {
			return fmt.Errorf("openapi --realm %s: %w", r, err)
		}
		if bytes.Contains(doc, []byte(humaErrorModel)) {
			return fmt.Errorf("openapi --realm %s describes errors with Huma's ErrorModel: problem.Install must run before the operations are registered", r)
		}
		if err := os.WriteFile(filepath.Join(dest, r+".openapi.yaml"), append([]byte(specHeader), doc...), 0o600); err != nil {
			return err
		}
	}
	return nil
}

// removeStaleSpecs deletes the documents in dir of realms that no longer exist.
func removeStaleSpecs(dir string, realms []string) error {
	files, err := filepath.Glob(filepath.Join(dir, "*.openapi.yaml"))
	if err != nil {
		return err
	}
	for _, f := range files {
		if realm := strings.TrimSuffix(filepath.Base(f), ".openapi.yaml"); !slices.Contains(realms, realm) {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}

// differing lists files under want and got (both relative to got's root) whose content differs or that
// exist on one side only.
func differing(want, got string) ([]string, error) {
	a, err := readTree(want)
	if err != nil {
		return nil, err
	}
	b, err := readTree(got)
	if err != nil {
		return nil, err
	}
	var out []string
	for name, content := range a {
		if other, ok := b[name]; !ok || !bytes.Equal(content, other) {
			out = append(out, filepath.Join(got, name))
		}
	}
	for name := range b {
		if _, ok := a[name]; !ok {
			out = append(out, filepath.Join(got, name))
		}
	}
	slices.Sort(out)
	return out, nil
}

func readTree(root string) (map[string][]byte, error) {
	out := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if errors.Is(err, fs.ErrNotExist) && path == root {
			return nil
		}
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		out[rel], err = os.ReadFile(path) //nolint:gosec // paths come from walking the generated tree
		return err
	})
	return out, err
}

func genDialect(ctx context.Context, dialect db.Dialect, adminURL string, fsys fs.FS, dest string) error {
	cfg := db.Defaults()
	cfg.MaxOpen, cfg.MaxIdle = 2, 2
	admin, _, err := db.OpenSQL(ctx, adminURL, cfg)
	if err != nil {
		return err
	}
	defer func() { _ = admin.Close() }()

	name := "keel_gen_" + clock.Wall(ctx).Now().Format("20060102150405") + "_" + rand.Text()[:8]
	quoted := `"` + name + `"`
	if dialect == db.MySQL {
		quoted = "`" + name + "`"
	}
	if _, err := admin.ExecContext(ctx, "CREATE DATABASE "+quoted); err != nil {
		return err
	}
	defer func() { _, _ = admin.ExecContext(context.WithoutCancel(ctx), "DROP DATABASE IF EXISTS "+quoted) }()

	scratchURL, err := withDatabase(adminURL, name)
	if err != nil {
		return err
	}
	scratch, _, err := db.OpenSQL(ctx, scratchURL, cfg)
	if err != nil {
		return err
	}
	defer func() { _ = scratch.Close() }()
	if _, err := migrate.New(scratch, dialect, fsys, migrate.Options{}).Up(ctx); err != nil {
		return err
	}

	switch dialect {
	case db.Postgres:
		return jetpostgres.GenerateDB(scratch, "public", dest, template.Default(postgres.Dialect).UseSchema(flat))
	case db.MySQL:
		return genMySQL(ctx, scratch, name, dest)
	}
	return nil
}

func flat(schema metadata.Schema) template.Schema {
	return template.DefaultSchema(schema).UsePath("")
}

// genMySQL maps char(36) columns (ids, D6) to uuid.UUID, skips goose's table, and writes tables
// without a database name so they work in any database, including per-package test databases.
func genMySQL(ctx context.Context, scratch *sql.DB, name, dest string) error {
	uuidCols, err := charIDColumns(ctx, scratch, name)
	if err != nil {
		return err
	}
	skip := func(table string) bool { return table == "goose_db_version" }
	tpl := template.Default(mysql.Dialect).UseSchema(func(schema metadata.Schema) template.Schema {
		return flat(schema).
			UseModel(template.DefaultModel().UseTable(func(table metadata.Table) template.TableModel {
				if skip(table.Name) {
					return template.TableModel{Skip: true}
				}
				return template.DefaultTableModel(table).UseField(func(col metadata.Column) template.TableModelField {
					f := template.DefaultTableModelField(col)
					if !uuidCols[table.Name+"."+col.Name] {
						return f
					}
					t := template.NewType(uuid.UUID{})
					if col.IsNullable {
						t = template.NewType(&uuid.UUID{})
					}
					return f.UseType(t)
				})
			})).
			UseSQLBuilder(template.DefaultSQLBuilder().UseTable(func(table metadata.Table) template.TableSQLBuilder {
				if skip(table.Name) {
					return template.TableSQLBuilder{Skip: true}
				}
				return template.DefaultTableSQLBuilder(table)
			}))
	})
	if err := jetmysql.GenerateDB(scratch, name, dest, tpl); err != nil {
		return err
	}
	return unqualify(filepath.Join(dest, "table"), name)
}

func charIDColumns(ctx context.Context, conn *sql.DB, schema string) (map[string]bool, error) {
	rows, err := conn.QueryContext(ctx,
		`SELECT table_name, column_name FROM information_schema.columns
		WHERE table_schema = ? AND column_type = 'char(36)' AND collation_name = 'ascii_bin'`, schema)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	out := map[string]bool{}
	for rows.Next() {
		var table, column string
		if err := rows.Scan(&table, &column); err != nil {
			return nil, err
		}
		out[table+"."+column] = true
	}
	return out, rows.Err()
}

func unqualify(dir, schema string) error {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	for _, f := range files {
		src, err := os.ReadFile(f) //nolint:gosec // generated files under internal/dbgen
		if err != nil {
			return err
		}
		out := bytes.ReplaceAll(src, []byte(`("`+schema+`", `), []byte(`("", `))
		if strings.Contains(string(out), schema) {
			return fmt.Errorf("%s still names the scratch database", f)
		}
		if err := os.WriteFile(f, out, 0o600); err != nil { //nolint:gosec // f comes from globbing internal/dbgen
			return err
		}
	}
	return nil
}
